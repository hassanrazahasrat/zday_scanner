    async def fingerprint(self, target, http_client) -> List:
        """Perform WAF fingerprinting"""
        from src.core.models import Fingerprint

        results = []

        try:
            # First try HEAD request
            resp = await http_client.head(target.url)

            # If needed, also GET for body patterns
            get_resp = None
            if resp.status != 200:
                get_resp = await http_client.get_with_browser_headers(target.url)

            use_resp = get_resp if get_resp else resp

            data = {
                "url": str(use_resp.url),
                "headers": {k.lower(): v for k, v in use_resp.headers.items()},
                "cookies": use_resp.cookies,
                "body": use_resp.text,
            }

            for sig in self.signatures:
                fp = self._match_signature(sig, data)
                if fp:
                    results.append(fp)

        except Exception:
            pass

        return results
