"""
ZDay Scanner - Markdown Reporter
Documentation-ready Markdown output
"""
from typing import Dict, List

from src.reporting.base import BaseReporter, ReportOptions
from src.core.models import ScanResult, Vulnerability, Technology


class MarkdownReporter(BaseReporter):
    """Markdown report generator"""

    def get_extension(self) -> str:
        return ".md"

    def generate(self, result: ScanResult) -> str:
        """Generate Markdown report"""

        vulns = self._filter_vulnerabilities(result.vulnerabilities)

        lines = []

        # Header
        lines.append(f"# ZDay Scanner Report")
        lines.append(f"")
        lines.append(f"**Target:** {result.target.url}")
        lines.append(f"**Scan ID:** {result.scan_id}")
        lines.append(f"**Date:** {result.start_time.isoformat() if result.start_time else 'N/A'}")
        lines.append(f"**Duration:** {result.duration:.2f}s")
        lines.append(f"")
        lines.append(f"---")
        lines.append(f"")

        # Summary
        lines.append(f"## Summary")
        lines.append(f"")
        lines.append(f"| Metric | Value |")
        lines.append(f"|--------|-------|")
        lines.append(f"| Total Vulnerabilities | {len(vulns)} |")

        by_sev = self._count_by_severity(vulns)
        for sev in ["critical", "high", "medium", "low", "info"]:
            if by_sev.get(sev, 0) > 0:
                lines.append(f"| {sev.title()} | {by_sev[sev]} |")

        lines.append(f"| Technologies Detected | {len(result.technologies)} |")
        lines.append(f"")

        # Vulnerabilities by severity
        if self.options.include_vulnerabilities and vulns:
            lines.append(f"## Vulnerabilities")
            lines.append(f"")

            grouped = self._group_vulns_by_severity(vulns)
            for sev in ["critical", "high", "medium", "low", "info"]:
                if sev in grouped:
                    lines.append(f"### {sev.title()} Severity")
                    lines.append(f"")

                    for vuln in grouped[sev]:
                        lines.append(f"#### {vuln.title}")
                        lines.append(f"")
                        lines.append(f"- **Type:** {vuln.type.value}")
                        lines.append(f"- **Location:** {vuln.location}")
                        if vuln.parameter:
                            lines.append(f"- **Parameter:** {vuln.parameter}")
                        if vuln.payload:
                            lines.append(f"- **Payload:** `{vuln.payload}`")
                        lines.append(f"- **Description:** {vuln.description}")

                        if self.options.include_evidence and vuln.evidence:
                            lines.append(f"- **Evidence:** {vuln.evidence}")

                        if self.options.include_remediation and vuln.remediation:
                            lines.append(f"- **Remediation:** {vuln.remediation}")

                        if vuln.cwe:
                            lines.append(f"- **CWE:** {vuln.cwe}")
                        if vuln.cvss:
                            lines.append(f"- **CVSS:** {vuln.cvss} (Score: {vuln.cvss_score})")
                        if vuln.references:
                            lines.append(f"- **References:**")
                            for ref in vuln.references:
                                lines.append(f"  - {ref}")

                        lines.append(f"- **Scanner Module:** {vuln.scanner_module}")
                        lines.append(f"- **Confidence:** {vuln.confidence:.0%}")
                        lines.append(f"")

        # Technologies
        if self.options.include_technologies and result.technologies:
            lines.append(f"## Technologies Detected")
            lines.append(f"")

            grouped = self._group_tech_by_category(result.technologies)
            for cat, techs in grouped.items():
                lines.append(f"### {cat.title()}")
                lines.append(f"")
                lines.append(f"| Technology | Version | Confidence | Evidence |")
                lines.append(f"|------------|---------|------------|----------|")

                for tech in techs:
                    evidence = "; ".join(tech.evidence[:2]) if self.options.include_evidence else ""
                    if len(evidence) > 50:
                        evidence = evidence[:47] + "..."
                    lines.append(f"| {tech.name} | {tech.version or 'N/A'} | {tech.confidence:.0%} | {evidence} |")

                lines.append(f"")

        # Footer
        lines.append(f"---")
        lines.append(f"")
        lines.append(f"*Report generated by ZDay Scanner v1.0.0*")

        return "\n".join(lines)

    def _count_by_severity(self, vulns) -> Dict[str, int]:
        counts = {}
        for v in vulns:
            sev = v.severity.value
            counts[sev] = counts.get(sev, 0) + 1
        return counts
